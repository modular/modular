using ShapeInferenceFunction =
    llvm::function_ref<std::optional<SmallVector<int64_t>>(InvokeShapeFuncOp,
                                                           TargetInfoAttr)>;

static ShapeInferenceFunction
getShapeInferencePackingFunction(InvokeShapeFuncOp invoke) {
  if (invoke.getShapeFuncName() == "pack_matmul_b_shape_func")
    return materializePackMatmulShapeFunc;
  if (invoke.getShapeFuncName() == "pack_conv_filter_shape")
    return materializePackConvFilterShape;
  if (invoke.getShapeFuncName() == "pack_conv_transpose_filter_shape")
    return materializePackConvTransposeFilterShape;
  return nullptr;
}

static void initLLVM() {
  static std::once_flag flag;

  std::call_once(flag, []() { llvm::InitializeNativeTarget(); });
}

// Reads target info from the graph's `target` attribute (so tests are
// host-independent), or from the current host when `useHostSystem` is set.
static ErrorOr<TargetInfoAttr> getTargetInfoForHost(GraphOp graph,
                                                    bool useHostSystem) {
  if (!useHostSystem) {
    if (auto target = graph->getAttrOfType<TargetInfoAttr>("target"))
      return target;
    return Error("unable to extract target information from graph");
  }

  MLIRContext *ctx = graph.getContext();

  initLLVM();
  return M::getTargetInfoFor(ctx, llvm::sys::getDefaultTargetTriple(),
                             llvm::sys::getHostCPUName(),
                             M::getHostCPUFeatures());
}

// Adds runtime assertions that the C++-computed shapes match the Mojo shape
// functions, by renaming each mo.invoke_shape_func output parameter and
// asserting it equals the computed one.
//
// clang-format off
//
//    // Newly computed dim
//    kgen.param.declare F = <1>
//
//    // Original shape function call
//    mo.invoke_shape_func['foo']<() -> F>()
//
//    ==>
//
//    kgen.param.declare F = <1>
//
//    // Shape function with updated output parameter
//    mo.invoke_shape_func['foo']<() -> F1>()
//
//    // Assert the new parameter equals the newly computed dim
//    kgen.param.declare var_eq: i1 = <eq(F, F1)>
//    kgen.param.declare assert3: !mo.chain = <apply(:(i1) -> !mo.chain "mo.assert"{message = "..." : !kgen.string}, var_eq)>
//
// clang-format on
static void addSanityChecks(GraphOp graph, InvokeShapeFuncOp invoke,
                            MutableArrayRef<KGEN::ParamDeclareOp> newDecls) {
  SmallVector<ParamBinding> bindings;
  ParamExprBuilder exprBuilder{graph, invoke.getLoc(), &bindings};

  SmallVector<ParamDeclAttr> newOutputParams;
  for (auto [newDecl, oldParam] :
       llvm::zip(newDecls, invoke.getOutputParamDecls())) {

    KGEN::ParamDeclAttr newOutputParam = graph.getNewParamOfType(
        oldParam.getName().strref(), oldParam.getType());
    newOutputParams.push_back(newOutputParam);

    auto outputParamRef = KGEN::ParamDeclRefAttr::get(newOutputParam);
    auto newDeclParamRef =
        KGEN::ParamDeclRefAttr::get(newDecl.getParamDeclAttr());

    auto outputParamVar = exprBuilder.createVar(outputParamRef);
    auto newDeclParamVar = exprBuilder.createVar(newDeclParamRef);
    exprBuilder.createAssert(
        outputParamVar == newDeclParamVar,
        "shape generated by C++ shape function does not match the Mojo "
        "implementation");
  }

  invoke.setOutputParamDecls(newOutputParams);

  OpBuilder builder(invoke.getContext());
  builder.setInsertionPointAfter(invoke);

  for (auto binding : bindings)
    binding.toOp(invoke.getLoc(), builder);
}

//===----------------------------------------------------------------------===//
// InvokeShapePackingFunctions pass.
//===----------------------------------------------------------------------===//

struct InvokeShapePackingFunctions
    : public impl::InvokeShapePackingFunctionsBase<
          InvokeShapePackingFunctions> {
  using Base::Base;

  void runOnOperation() override {
    GraphOp graph = getOperation();

    ErrorOr<TargetInfoAttr> targetOr =
        getTargetInfoForHost(graph, useHostSystem);

    if (failed(targetOr)) {
      signalPassFailure();
      return;
    }

    TargetInfoAttr targetInfo = targetOr.takeValue();

    graph.walk([&](InvokeShapeFuncOp invoke) {
      ShapeInferenceFunction infer = getShapeInferencePackingFunction(invoke);
      if (!infer)
        return WalkResult::advance();

      std::optional<llvm::SmallVector<int64_t>> maybeInferredShapes =
          infer(invoke, targetInfo);

      if (!maybeInferredShapes) {
        invoke.emitRemark("unable to infer shapes for operation");
        return WalkResult::advance();
      }

      SmallVector<int64_t> inferredShapes = std::move(*maybeInferredShapes);

      ArrayRef<ParamDeclAttr> outputDecls = invoke.getOutputParamDecls();
      if (outputDecls.size() != inferredShapes.size()) {
        invoke.emitError("number of inferred parameters does not match number "
                         "of output parameters");
        return WalkResult::interrupt();
      }

      SmallVector<KGEN::ParamDeclareOp> newDecls;
      newDecls.reserve(outputDecls.size());

      OpBuilder rewriter(invoke);
      for (auto [decl, value] : llvm::zip(outputDecls, inferredShapes)) {
        auto valueAttr = ShapeAttr::getDim(&getContext(), value);
        auto newDecl = KGEN::ParamDeclareOp::create(rewriter, invoke.getLoc(),
                                                    decl, valueAttr);
        newDecls.push_back(newDecl);
      }

      if (sanityCheckShapeFuncs)
        addSanityChecks(graph, invoke, newDecls);
      else
        invoke.erase();

      return WalkResult::advance();
    });
  }
};

